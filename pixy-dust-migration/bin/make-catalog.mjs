#!/usr/bin/env node
// Generate extension-v0.2/catalog.js from the reconcile output, so the
// extension's embedded id list is regenerated from the live exports instead of
// being hand-frozen. v0.1 baked in 424 ids on 09-13; two days later 34 of them
// were dead listings and 35 new listings were missing entirely.

import { readFile, writeFile } from 'node:fs/promises';

const argv = process.argv.slice(2);
const arg = (f, d) => { const i = argv.indexOf(f); return i > -1 && argv[i + 1] ? argv[i + 1] : d; };

const reconcile = JSON.parse(await readFile(arg('--reconcile', 'data/reconcile.json'), 'utf8'));
const ids = reconcile.migratable.map((m) => m.ebayItemId);
const out = arg('--out', 'extension-v0.2/catalog.js');

await writeFile(out, `// GENERATED by bin/make-catalog.mjs — do not edit by hand.
// Source: ${reconcile.sources.square}
//         ${reconcile.sources.ebay}
// Generated: ${reconcile.generatedAt}
// Listings that are live on eBay AND have a matching Square EB-* item.
const PIXY_DUST_ITEM_IDS = ${JSON.stringify(ids, null, 0).replace(/","/g, '", "')};
const PIXY_DUST_CATALOG_GENERATED_AT = ${JSON.stringify(reconcile.generatedAt)};
`);
console.log(`wrote ${out} with ${ids.length} listing ids`);
